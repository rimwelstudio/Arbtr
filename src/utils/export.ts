import { DecisionAnalysisResult } from '../types';

export function formatDecisionAsMarkdown(decision: DecisionAnalysisResult): string {
  const lines: string[] = [];

  lines.push(`# Arbitr: Decision Analysis Report`);
  lines.push(`**Decision:** ${decision.title}`);
  lines.push(`**Date:** ${new Date(decision.createdAt).toLocaleDateString()}`);
  if (decision.context) {
    lines.push(`**Context:** ${decision.context}`);
  }
  lines.push(``);

  lines.push(`---`);
  lines.push(`## 🏆 Arbitr Verdict`);
  lines.push(`**Winning Recommendation:** ${decision.verdict.recommendedOptionName}`);
  lines.push(`**Confidence Level:** ${decision.verdict.confidenceScore}%`);
  lines.push(`**The Decisive Pivot Point:** ${decision.verdict.theTiebreakerFactor}`);
  lines.push(``);
  lines.push(`### Executive Reasoning`);
  lines.push(decision.verdict.coreReasoning);
  lines.push(``);

  if (decision.verdict.regretMinimizationCheck) {
    lines.push(`### 10-10-10 Regret Minimization Check`);
    lines.push(decision.verdict.regretMinimizationCheck);
    lines.push(``);
  }

  if (decision.verdict.gutCheckQuestion) {
    lines.push(`### Intuitive Gut-Check`);
    lines.push(`*"${decision.verdict.gutCheckQuestion}"*`);
    lines.push(``);
  }

  lines.push(`### Immediate Action Steps`);
  if (Array.isArray(decision.verdict.actionPlan) && decision.verdict.actionPlan.length > 0) {
    decision.verdict.actionPlan.forEach((step: any, idx: number) => {
      if (typeof step === 'string') {
        lines.push(`${idx + 1}. ${step}`);
      } else if (typeof step === 'object' && step !== null) {
        const title = step.title || step.action || step.task || step.name || `Step ${idx + 1}`;
        const desc = step.description || step.detail || step.details || step.text || '';
        if (desc && desc !== title) {
          lines.push(`${idx + 1}. **${title}:** ${desc}`);
        } else {
          lines.push(`${idx + 1}. **${title}**`);
        }
      }
    });
  }
  lines.push(``);

  lines.push(`---`);
  lines.push(`## ⚖️ Pros & Cons Breakdown`);
  decision.options.forEach((opt) => {
    lines.push(`### Option: ${opt.name} (Score: ${opt.score}/100)`);
    lines.push(`*${opt.summary}*`);
    lines.push(``);
    lines.push(`**Pros:**`);
    opt.pros.forEach((p) => {
      lines.push(`- **[${p.impact.toUpperCase()}]** ${p.text} ${p.rationale ? `— *${p.rationale}*` : ''}`);
    });
    lines.push(``);
    lines.push(`**Cons:**`);
    opt.cons.forEach((c) => {
      lines.push(`- **[${c.impact.toUpperCase()}]** ${c.text} ${c.rationale ? `— *${c.rationale}*` : ''}`);
      if (c.mitigation) {
        lines.push(`  - *Mitigation:* ${c.mitigation}`);
      }
    });
    lines.push(``);
  });

  lines.push(`---`);
  lines.push(`## 📊 Comparison Matrix`);
  lines.push(`*${decision.comparisonMatrix.analysisSummary}*`);
  lines.push(``);
  lines.push(`| Criteria | Weight | ${decision.options.map(o => o.name).join(' | ')} | Advantage |`);
  lines.push(`| --- | --- | ${decision.options.map(() => '---').join(' | ')} | --- |`);
  decision.comparisonMatrix.criteria.forEach((c) => {
    const scores = decision.options.map(o => `${c.scores[o.id] || '-'}/10`).join(' | ');
    const leading = decision.options.find(o => o.id === c.leadingOptionId)?.name || '-';
    lines.push(`| **${c.name}** | ${c.importanceWeight}x | ${scores} | ${leading} |`);
  });
  lines.push(``);

  lines.push(`---`);
  lines.push(`## 🧭 SWOT Strategic Analysis`);
  decision.options.forEach((opt) => {
    const swot = decision.swotAnalysis[opt.id];
    if (!swot) return;
    lines.push(`### SWOT for ${opt.name}`);
    lines.push(`- **Strengths:** ${swot.strengths.join(', ')}`);
    lines.push(`- **Weaknesses:** ${swot.weaknesses.join(', ')}`);
    lines.push(`- **Opportunities:** ${swot.opportunities.join(', ')}`);
    lines.push(`- **Threats:** ${swot.threats.join(', ')}`);
    if (swot.strategicImplication) {
      lines.push(`- **Strategic Implication:** ${swot.strategicImplication}`);
    }
    lines.push(``);
  });

  const siteUrl = typeof window !== 'undefined' ? window.location.origin : 'https://arbitrapps.com';
  lines.push(`Generated by Arbitr Decision Engine — ${siteUrl} (@arbitrapps)`);
  return lines.join('\n');
}
